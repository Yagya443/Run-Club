import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAuth } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import * as c from '../controllers/authController.js';
import * as nc from '../controllers/runnerController.js';
import * as sc from '../controllers/socialController.js';
import * as lc from '../controllers/lifecycleController.js';
import * as rc from '../controllers/routeController.js';

const r = Router();
const authLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false,
  message: { error: 'Too many attempts. Try again in a few minutes.' } });

r.get('/health', (_req, res) => res.json({ ok: true }));
r.post('/auth/register', authLimiter, validate(c.registerSchema), c.register);
r.post('/auth/login', authLimiter, validate(c.loginSchema), c.login);
r.get('/auth/me', requireAuth, c.me);
r.get('/dashboard', requireAuth, c.dashboard);
const routeLimiter = rateLimit({ windowMs: 60 * 1000, limit: 12, standardHeaders: true, legacyHeaders: false, message: { error: 'Slow down a little and try again in a minute.' } });
r.get('/geocode', requireAuth, routeLimiter, rc.search);
r.post('/routes/generate', requireAuth, routeLimiter, validate(rc.generateSchema), rc.generate);
r.post('/routes/save', requireAuth, validate(rc.saveSchema), rc.save);
r.get('/runners/nearby', requireAuth, routeLimiter, nc.nearby);
r.post('/runners/match', requireAuth, routeLimiter, validate(nc.matchSchema), nc.match);
r.post('/runs/plan', requireAuth, routeLimiter, validate(nc.planSchema), nc.plan);
r.post('/runs/create', requireAuth, validate(nc.createSchema), nc.create);
r.get('/ai/status', requireAuth, nc.status);
const social = rateLimit({ windowMs: 60 * 1000, limit: 60, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many actions. Try again shortly.' } });
const A = requireAuth;
r.get('/runs/discover', A, sc.discover);
r.get('/runs/:id', A, sc.getRun);
r.post('/runs/:id/join', A, social, sc.joinRun);
r.post('/runs/:id/leave', A, social, sc.leaveRun);
r.put('/runs/:id/visibility', A, validate(sc.visibilitySchema), sc.visibility);
r.post('/runs/:id/kudos', A, social, sc.giveKudos);
r.delete('/runs/:id/kudos', A, social, sc.removeKudos);
r.post('/runs/:id/comments', A, social, validate(sc.commentSchema), sc.comment);
r.delete('/runs/:id/comments/:cid', A, sc.delComment);
r.get('/clubs', A, sc.listClubs);
r.post('/clubs', A, social, validate(sc.clubSchema), sc.createClub);
r.get('/clubs/:id', A, sc.getClub);
r.post('/clubs/:id/join', A, social, sc.joinClub);
r.post('/clubs/:id/leave', A, social, sc.leaveClub);
r.get('/users/:id', A, sc.getProfile);
r.put('/me/profile', A, validate(sc.profileSchema), sc.updateProfile);
r.post('/users/:id/follow', A, social, sc.follow);
r.delete('/users/:id/follow', A, social, sc.unfollow);
r.post('/runs/:id/start', A, social, validate(lc.startSchema), lc.start);
r.post('/runs/:id/complete', A, social, validate(lc.completeSchema), lc.complete);
r.post('/runs/:id/discard', A, social, lc.discard);
r.post('/runs/:id/reflection', A, routeLimiter, validate(lc.reflectionSchema), lc.reflection);
r.get('/stats', A, lc.stats);
export default r;
